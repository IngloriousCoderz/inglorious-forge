export const About = {
  click(entity) {
    entity.name += "!"
  },

  render(entity, api) {
    return (
      <div>
        <h1>
          About{" "}
          <span onClick={() => api.notify(`#${entity.id}:click`)}>
            {entity.name}
          </span>
        </h1>
        <p>This is a static page generated by SSX.</p>
        <a href="/">Back Home</a>
      </div>
    )
  },
}

export const metadata = {
  title: "About",
}
